"""Extract editable UFO masters and a designspace from a released Dastkhat variable font.

Usage: python3 -I extract_ufo.py <Family[wght].ttf> <out_dir> "<Family Name>"

Masters are Thin (100), Regular (400) and Black (900). Kerning, mark and mkmk
features are regenerated by ufo2ft from kerning.plist and glyph anchors; the
GSUB lookups and the contextual Arabic kerning adjustments stay in features.fea.
Rebuild with:  fontmake -m <Family>.designspace -o variable
"""
import sys, re, os, warnings
warnings.filterwarnings('ignore')
import extractor, ufoLib2
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.designspaceLib import DesignSpaceDocument, SourceDescriptor, AxisDescriptor, InstanceDescriptor

vfpath, outdir, fam = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(outdir, exist_ok=True)
vf = TTFont(vfpath)
seg = vf['avar'].segments['wght']          # normalized from->to
CAT = {1: 'base', 2: 'ligature', 3: 'mark', 4: 'component'}
cats = {g: CAT[c] for g, c in vf['GDEF'].table.GlyphClassDef.classDefs.items()}

KILL = re.compile(r'(PairPositioning|MarkToBase|MarkToMark|MarkToLigature)')
def strip_gpos(fea):
    """Drop kerning and mark lookups (regenerated by ufo2ft from kerning.plist and glyph anchors),
    keep the contextual single-adjustment lookups and every GSUB lookup."""
    blocks, cur = [], []
    for line in fea.split('\n'):
        cur.append(line)
        if re.match(r'^\} [\w.]+;$', line) or re.match(r'^(languagesystem|table GDEF)', line) and line.endswith(';'):
            blocks.append('\n'.join(cur)); cur = []
    blocks.append('\n'.join(cur))
    out = []
    for b in blocks:
        head = b.strip().split('\n')[0] if b.strip() else ''
        if head.startswith('table GDEF'): continue
        if head.startswith('lookup') and KILL.match(head.split()[1]): continue
        if head.startswith('feature'):
            tag = head.split()[1]
            if tag in ('mark', 'mkmk') or KILL.search(b): continue
        out.append(b)
    return '\n'.join(out)

for w in (100, 400, 900):
    m = instancer.instantiateVariableFont(TTFont(vfpath), {'wght': w}, inplace=False)
    tmp = os.path.join(outdir, f'_m{w}.ttf'); m.save(tmp)
    u = ufoLib2.Font(); extractor.extractUFO(tmp, u); os.remove(tmp)
    u.lib.pop('public.truetype.instructions', None)
    for g in u: g.lib.pop('public.truetype.instructions', None)
    u.features.text = strip_gpos(u.features.text)
    u.lib['public.openTypeCategories'] = {g: c for g, c in cats.items() if g in u}
    u.lib['com.github.googlei18n.ufo2ft.featureWriters'] = [
        {'class': 'KernFeatureWriter', 'options': {'mode': 'append'}},
        {'class': 'MarkFeatureWriter'}, {'class': 'GdefFeatureWriter'}]
    u.info.styleName = {100: 'Thin', 400: 'Regular', 900: 'Black'}[w]
    u.info.familyName = fam
    u.save(os.path.join(outdir, f'{fam.replace(" ","")}-{u.info.styleName}.ufo'), overwrite=True)

ds = DesignSpaceDocument()
ax = AxisDescriptor(); ax.tag = 'wght'; ax.name = 'Weight'; ax.minimum, ax.default, ax.maximum = 100, 400, 900
def lerp2(n):  # normalized coordinate -> weight value
    return 400 + n * 300 if n < 0 else 400 + n * 500
ax.map = [(round(lerp2(a)), round(lerp2(b), 2)) for a, b in seg.items()]
ds.addAxis(ax)
for w, st in ((100, 'Thin'), (400, 'Regular'), (900, 'Black')):
    s = SourceDescriptor(); s.filename = f'{fam.replace(" ","")}-{st}.ufo'; s.name = st
    s.familyName = fam; s.styleName = st; s.location = {'Weight': w}; ds.addSource(s)
for w, st in ((100, 'Thin'), (200, 'ExtraLight'), (300, 'Light'), (400, 'Regular'), (500, 'Medium'),
              (600, 'SemiBold'), (700, 'Bold'), (800, 'ExtraBold'), (900, 'Black')):
    i = InstanceDescriptor(); i.familyName = fam; i.styleName = st; i.name = f'{fam} {st}'
    i.userLocation = {'Weight': w}; ds.addInstance(i)
ds.write(os.path.join(outdir, f'{fam.replace(" ","")}.designspace'))
print(ax.map)
